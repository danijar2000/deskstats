#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_locale_picks_its_language() {
        assert_eq!(language_of("ru-KG"), Language::Ru);
        assert_eq!(language_of("pt_BR.UTF-8"), Language::Pt);
        assert_eq!(language_of("zh-Hans-CN"), Language::Zh);
        assert_eq!(language_of(""), Language::En);
        assert_eq!(language_of("C"), Language::En);
        for language in [Language::En, Language::Ru, Language::De, Language::Es, Language::Fr, Language::Pt, Language::Zh, Language::Ja] {
            assert!(words(language).phone_ago.contains("{}"));
        }
    }
}
