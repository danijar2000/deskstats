//! The words of the window, in the languages of the phone app.

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Language {
    En,
    Ru,
    De,
    Es,
    Fr,
    Pt,
    Zh,
    Ja,
}

pub struct Words {
    pub running: &'static str,
    pub stopped: &'static str,
    pub old: &'static str,
    pub checking: &'static str,
    pub start: &'static str,
    pub computer: &'static str,
    pub name: &'static str,
    pub address: &'static str,
    pub no_network: &'static str,
    pub wifi: &'static str,
    pub wifi_on: &'static str,
    pub wifi_off: &'static str,
    pub usb: &'static str,
    pub usb_on: &'static str,
    pub usb_off: &'static str,
    pub phone: &'static str,
    pub phone_now: &'static str,
    pub phone_never: &'static str,
    /// "{}" is the time, like "5 min".
    pub phone_ago: &'static str,
    pub seconds: &'static str,
    pub minutes: &'static str,
    pub hours: &'static str,
    pub connect: &'static str,
    pub steps: [&'static str; 3],
    pub copy: &'static str,
    pub copied: &'static str,
    pub restart: &'static str,
    pub forget: &'static str,
    pub forget_question: &'static str,
    pub forget_yes: &'static str,
    pub cancel: &'static str,
    pub failed: &'static str,
    pub open: &'static str,
    pub quit: &'static str,
}

pub fn language_of(locale: &str) -> Language {
    match locale.get(..2).unwrap_or("").to_ascii_lowercase().as_str() {
        "ru" | "uk" | "be" | "kk" | "ky" => Language::Ru,
        "de" => Language::De,
        "es" => Language::Es,
        "fr" => Language::Fr,
        "pt" => Language::Pt,
        "zh" => Language::Zh,
        "ja" => Language::Ja,
        _ => Language::En,
    }
}

/// The language of the system; DESKSTATS_LANGUAGE (like "ru") overrides it.
pub fn system_language() -> Language {
    let chosen = std::env::var("DESKSTATS_LANGUAGE").ok().filter(|value| !value.is_empty());
    language_of(&chosen.or_else(sys_locale::get_locale).unwrap_or_default())
}

pub fn words(language: Language) -> &'static Words {
    match language {
        Language::En => &EN,
        Language::Ru => &RU,
        Language::De => &DE,
        Language::Es => &ES,
        Language::Fr => &FR,
        Language::Pt => &PT,
        Language::Zh => &ZH,
        Language::Ja => &JA,
    }
}

